import { flipLogoSvg } from "./pdfLogo";
import { downloadBlob } from "./files";
import { iconSvg } from "./categoryIcons";

export const SITE_URL = "flipr-convert.pages.dev"; // change this to your real website address

export interface Report {
  categoryLabel: string;
  categoryIcon: string;
  fromCode: string;
  toCode: string;
  fromDisplay: string;   // e.g. "$ 2,000" or "2 kg"
  toDisplay: string;
  notes: Array<{ title: string; text: string }>;
  calcTitle: string;
  calcLines: string[];
  fileName: string;
}

type Kids = Array<HTMLElement | string>;
function el(tag: string, style: string, kids: Kids | string = []): HTMLElement {
  const node = document.createElement(tag);
  node.style.cssText = style;
  if (typeof kids === "string") node.textContent = kids;
  else for (const k of kids) node.append(k);
  return node;
}

function iconNode(id: string, size: number): HTMLElement {
  const img = document.createElement("img");
  img.src = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(iconSvg(id, size)); // fixed SVG text from categoryIcons.ts
  img.style.cssText = `width:${size}px;height:${size}px;display:inline-block;vertical-align:middle;margin-right:8px;`;
  return img;
}

/** The logo from the Figma "Downloaded Result" frame (hand icon + FLIP). */
function logoNode(): HTMLElement {
  const img = document.createElement("img");
  img.src = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(flipLogoSvg());
  img.style.cssText = "width:134px;height:52.6px;display:block;";
  return img;
}

function buildNode(r: Report): HTMLElement {
  const grey = "background:#e7e7e7;border-radius:20px;padding:20px;margin-top:24px;";
  const chip = (kids: Kids | string) =>
    el("div", "display:inline-block;background:#fff;border-radius:10px;padding:8px 16px;font-size:14px;line-height:20px;font-weight:500;margin-bottom:14px;white-space:nowrap;color:#1b1b1b;", kids);


  const side = (label: string, value: string) =>
    el("div", "flex:1;min-width:0;", [
      el("div", "font-size:12px;color:#515151;", label),
      el("div", "font-size:22px;margin-top:6px;word-break:break-word;", value)
    ]);

  const root = el("div", "width:720px;padding:32px;background:#f3f3f3;font-family:Roboto,Arial,sans-serif;color:#1b1b1b;box-sizing:border-box;", [
    el("div", "display:flex;justify-content:space-between;align-items:center;", [
      logoNode(),
      el("span", "font-size:14px;font-weight:700;", SITE_URL)
    ]),
    el("div", grey, [
      chip([iconNode(r.categoryIcon, 20), el("span", "color:#1b1b1b;vertical-align:middle;", r.categoryLabel)]),
      el("div", "background:#fff;border-radius:14px;padding:16px 20px;display:flex;align-items:center;gap:16px;", [
        side(`From: ${r.fromCode}`, r.fromDisplay),
        el("div", "color:#1e4fbc;font-size:26px;", "→"),
        side(`To: ${r.toCode}`, r.toDisplay)
      ])
    ]),
    el("div", "margin-top:24px;padding:0 6px;", r.notes.flatMap((n) => [
      el("div", "font-size:16px;font-weight:700;margin-top:14px;", `• ${n.title}`),
      el("div", "font-size:15px;line-height:1.6;color:#333;margin-top:6px;", n.text)
    ])),
    el("div", grey, [
      chip(r.calcTitle),
      el("div", "background:#fff;border-radius:14px;padding:18px 20px;font-size:15px;line-height:1.8;", r.calcLines.map((l) => el("div", "", l)))
    ]),
    el("div", "margin-top:20px;font-size:11px;color:#878787;text-align:center;", `Generated by Flipr · ${new Date().toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" })}`)
  ]);
  return root;
}

/** Renders the report the way the Figma "Downloaded Result" looks, then saves it as a PDF. */
export async function downloadResultPdf(report: Report): Promise<void> {
  const [{ default: html2canvas }, { jsPDF }] = await Promise.all([import("html2canvas"), import("jspdf")]);

  const node = buildNode(report);
  const holder = document.createElement("div");
  holder.style.cssText = "position:fixed;left:-10000px;top:0;";
  holder.append(node);
  document.body.append(holder);

  try {
    await document.fonts?.ready;
    await Promise.all(Array.from(node.querySelectorAll("img")).map((i) => i.decode().catch(() => undefined)));

    const canvas = await html2canvas(node, { scale: 2, backgroundColor: "#f3f3f3", useCORS: true });
    const pageW = 595.28; // A4 width in points
    const pageH = (canvas.height / canvas.width) * pageW;
    const pdf = new jsPDF({ unit: "pt", format: [pageW, pageH], orientation: pageH > pageW ? "portrait" : "landscape" });
    pdf.addImage(canvas.toDataURL("image/jpeg", 0.92), "JPEG", 0, 0, pageW, pageH);
    downloadBlob(pdf.output("blob"), report.fileName);
  } finally {
    holder.remove();
  }
}

export interface TranslationReport {
  fromLabel: string;
  toLabel: string;
  original: string;
  translated: string;
  fileName: string;
}

function buildTranslationNode(r: TranslationReport): HTMLElement {
  const grey = "background:#e7e7e7;border-radius:20px;padding:20px;margin-top:24px;";
  const chip = (text: string) =>
    el("div", "display:inline-flex;background:#fff;border-radius:10px;padding:8px 16px;font-size:14px;font-weight:500;margin-bottom:14px;", text);
  const textBox = (value: string) => {
    const box = el("div", "background:#fff;border-radius:14px;padding:16px 20px;font-size:16px;line-height:1.7;white-space:pre-wrap;word-break:break-word;", value);
    box.setAttribute("dir", "auto");
    return box;
  };

  return el("div", "width:720px;padding:32px;background:#f3f3f3;font-family:Roboto,Arial,sans-serif;color:#1b1b1b;box-sizing:border-box;", [
    el("div", "display:flex;justify-content:space-between;align-items:center;", [
      logoNode(),
      el("span", "font-size:14px;font-weight:700;", SITE_URL)
    ]),
    el("div", grey, [chip(`Original · ${r.fromLabel}`), textBox(r.original)]),
    el("div", grey, [chip(`Translation · ${r.toLabel}`), textBox(r.translated)]),
    el("div", "margin-top:20px;font-size:11px;color:#878787;text-align:center;", `Machine translation, so check anything important. Generated by Flipr · ${new Date().toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" })}`)
  ]);
}

